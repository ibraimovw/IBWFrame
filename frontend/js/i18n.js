export function getLang() {
  const store = getStore();
  if (store.preferences.lang === 'ru' || store.preferences.lang === 'en') {
    return store.preferences.lang;
  }
  const browserLang = (navigator.language || 'en').toLowerCase();
  return browserLang.startsWith('ru') ? 'ru' : 'en';
}

export function getTmdbLang() {
  return getLang() === 'ru' ? 'ru-RU' : 'en-US';
}

export function setLang(lang) {
  const normalized = lang === 'ru' ? 'ru' : 'en';
  updateStore((store) => {
    store.preferences.lang = normalized;
    return store;
  });
  document.documentElement.lang = normalized;
  applyStaticTranslations();
}

export function t(key) {
  const lang = getLang();
  return DICTIONARY[lang]?.[key] || DICTIONARY.en[key] || key;
}

export function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', t(key));
  });
  const langBtn = document.getElementById('lang-toggle');
  if (langBtn) langBtn.textContent = getLang().toUpperCase();
}
